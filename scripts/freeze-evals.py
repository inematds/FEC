#!/usr/bin/env python3
"""freeze-evals.py — calcula sha256 dos arquivos sob evals/v1/ (excl. runs/) e
compara com HASHES.lock. PLAN item 28a.

Uso:
    python scripts/freeze-evals.py            # regrava HASHES.lock
    python scripts/freeze-evals.py --verify   # exit 1 se mismatch
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LOCK = REPO / "evals/v1/HASHES.lock"
ROOT = REPO / "evals/v1"

EXCLUDE_DIRS = {"runs"}


def collect() -> dict[str, str]:
    """sha256 de cada arquivo sob evals/v1/, ordenado por path relativo."""
    out: dict[str, str] = {}
    for p in sorted(ROOT.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(ROOT)
        if rel.parts and rel.parts[0] in EXCLUDE_DIRS:
            continue
        if rel.name == "HASHES.lock":
            continue
        h = hashlib.sha256(p.read_bytes()).hexdigest()
        out[str(rel)] = h
    return out


def render_lock(hashes: dict[str, str]) -> str:
    lines = [
        "# FEC Eval Harness Hash Lock — v1",
        "# Generated by scripts/freeze-evals.py — do not edit by hand.",
        "# A mismatch blocks merge unless version (v1, v2, ...) is bumped.",
        "",
    ]
    for path, h in hashes.items():
        lines.append(f"{path}  {h}")
    lines.append("")
    return "\n".join(lines)


def parse_lock(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        if "  " not in line:
            continue
        path, h = line.rsplit("  ", 1)
        out[path.strip()] = h.strip()
    return out


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--verify", action="store_true")
    args = p.parse_args()

    current = collect()
    if not args.verify:
        LOCK.write_text(render_lock(current), encoding="utf-8")
        print(f"Wrote {LOCK.relative_to(REPO)} ({len(current)} entries)")
        return 0

    if not LOCK.exists():
        print("HASHES.lock missing. Run: python scripts/freeze-evals.py", file=sys.stderr)
        return 1

    expected = parse_lock(LOCK.read_text(encoding="utf-8"))
    diffs = []
    all_paths = set(current) | set(expected)
    for path in sorted(all_paths):
        c = current.get(path)
        e = expected.get(path)
        if c is None:
            diffs.append(f"REMOVED  {path}")
        elif e is None:
            diffs.append(f"ADDED    {path}  {c}")
        elif c != e:
            diffs.append(f"CHANGED  {path}  {e[:12]} → {c[:12]}")

    if diffs:
        print("HASHES.lock is stale. Bumping version of evals/v1 OR re-freezing required:", file=sys.stderr)
        for d in diffs:
            print("  " + d, file=sys.stderr)
        return 1
    print(f"OK — {len(current)} entries match.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
